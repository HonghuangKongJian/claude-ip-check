/**
 * 将两位国家码转换为中文名。
 *
 * Args:
 *   cc: ISO 3166-1 alpha-2 国家码。
 *
 * Returns:
 *   string: 中文名；未收录返回空字符串。
 */
export function ccToZh(cc) {
  if (!cc) return '';
  return CC_ZH[String(cc).toUpperCase()] || '';
}

/**
 * 归一化归属结果：补充中文国名字段。
 *
 * Args:
 *   geo: geoip.js 产出的归属对象。
 *
 * Returns:
 *   object: 附加 country_zh 后的对象。
 */
export function withZhName(geo) {
  if (!geo) return geo;
  return { ...geo, country_zh: ccToZh(geo.country_code) || geo.country || '' };
}
